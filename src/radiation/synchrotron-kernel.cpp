    [[nodiscard]] Real low_x_log2_kernel(Real log2_x) noexcept {
        // F(x) = 2^(2/3) Gamma(2/3) x^(1/3) - pi/sqrt(3) x + O(x^(7/3)).
        constexpr Real leading = 2.1495282415344786;
        constexpr Real linear = 1.8137993642342178;
        constexpr Real log2_leading = 1.1040200652661238;
        const Real correction = (linear / leading) * fast_exp2((2.0 / 3.0) * log2_x);
        return log2_leading + log2_x / 3.0 + std::log2(std::max(1.0 - correction, 0.0));
    }

    [[nodiscard]] Real high_x_log2_kernel(Real log2_x) noexcept {
        // F(x) = sqrt(pi*x/2) exp(-x) [1 + 55/(72x) - 10151/(10368x^2) + O(x^-3)].
        constexpr Real log2_pi_over_2 = 0.6514961294723187;
        constexpr Real inv_ln2 = 1.4426950408889634;
        if (log2_x > 1023) {
            return -con::inf;
        }
        const Real x = fast_exp2(log2_x);
        const Real inv_x = 1 / x;
        const Real correction = 1 + (55.0 / 72.0) * inv_x - (10151.0 / 10368.0) * inv_x * inv_x;
        return 0.5 * (log2_pi_over_2 + log2_x) - x * inv_ln2 + std::log2(correction);
    }

    [[nodiscard]] Real low_x_log2_absorption_kernel(Real log2_x) noexcept {
        // G(x) = 2^(2/3) Gamma(5/3) x^(1/3) [1 - 3x^2/8 + O(x^(10/3))].
        constexpr Real log2_leading = 0.51905756454496719;
        const Real x2 = fast_exp2(2 * log2_x);
        return log2_leading + log2_x / 3.0 + std::log2(1 - 3.0 / 8.0 * x2);
    }

    [[nodiscard]] Real high_x_log2_absorption_kernel(Real log2_x) noexcept {
        // G(x) = sqrt(pi/2) x^(3/2) exp(-x) [1 + 91/(72x) + 1729/(10368x^2) + O(x^-3)].
        constexpr Real log2_pi_over_2 = 0.6514961294723187;
        constexpr Real inv_ln2 = 1.4426950408889634;
        if (log2_x > 1023) {
            return -con::inf;
        }
        const Real x = fast_exp2(log2_x);
        const Real inv_x = 1 / x;
        const Real correction = 1 + (91.0 / 72.0) * inv_x + (1729.0 / 10368.0) * inv_x * inv_x;
        return 0.5 * log2_pi_over_2 + 1.5 * log2_x - x * inv_ln2 + std::log2(correction);
    }

    [[nodiscard]] Real interpolate_log2_table(std::array<Real, 183> const& values, Real log2_x) noexcept {
        const Real position = (log2_x - table_log2_start) / table_log2_step;
        const size_t i = static_cast<size_t>(position);
        const Real f = position - static_cast<Real>(i);
        const Real y0 = values[i - 1];
        const Real y1 = values[i];
        const Real y2 = values[i + 1];
        const Real y3 = values[i + 2];
        return y1 + 0.5 * f *
                        (y2 - y0 + f * (2 * y0 - 5 * y1 + 4 * y2 - y3 + f * (3 * (y1 - y2) + y3 - y0)));
    }
