Real log2_synchrotron_kernel(Real log2_x) noexcept {
    if (!std::isfinite(log2_x)) {
        return -con::inf;
    }
    if (log2_x < table_log2_x_min) {
        return low_x_log2_kernel(log2_x);
    }
    if (log2_x > table_log2_x_max) {
        return high_x_log2_kernel(log2_x);
    }

    // Four-point cubic interpolation on the uniform log2 lattice.
    return interpolate_log2_table(log2_kernel, log2_x);
}

Real synchrotron_kernel(Real x) noexcept {
    if (!(x > 0) || !std::isfinite(x)) {
        return 0;
    }
    const Real log2_value = log2_synchrotron_kernel(fast_log2(x));
    constexpr Real log2_smallest = -1074;
    return (log2_value > log2_smallest) ? fast_exp2(log2_value) : 0;
}

Real log2_synchrotron_absorption_kernel(Real log2_x) noexcept {
    if (!std::isfinite(log2_x)) {
        return -con::inf;
    }
    if (log2_x < table_log2_x_min) {
        return low_x_log2_absorption_kernel(log2_x);
    }
    if (log2_x > table_log2_x_max) {
        return high_x_log2_absorption_kernel(log2_x);
    }
    return interpolate_log2_table(log2_absorption_kernel, log2_x);
}

Real synchrotron_absorption_kernel(Real x) noexcept {
    if (!(x > 0) || !std::isfinite(x)) {
        return 0;
    }
    const Real log2_value = log2_synchrotron_absorption_kernel(fast_log2(x));
    constexpr Real log2_smallest = -1074;
    return (log2_value > log2_smallest) ? fast_exp2(log2_value) : 0;
}
